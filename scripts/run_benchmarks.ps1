param(
  [int]$Jobs = 4,
  [string]$Output = "benchmarks/results/latest.csv"
)

$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
Set-Location $repoRoot

function Write-Workload {
  param([string]$Name, [int]$TaskCount, [string]$Shape)
  $dir = Join-Path $repoRoot "benchmarks/generated/$Name"
  New-Item -ItemType Directory -Force -Path (Join-Path $dir "out") | Out-Null
  $scriptPath = Join-Path $dir "write_task.py"
  @'
from pathlib import Path
import sys

name, output = sys.argv[1], sys.argv[2]
Path(output).parent.mkdir(parents=True, exist_ok=True)
Path(output).write_text(f"{name}\n", encoding="utf-8")
'@ | Set-Content -Encoding UTF8 $scriptPath

  $lines = @("# generated by scripts/run_benchmarks.ps1", "")
  $taskNames = @()
  $nonBuild = $TaskCount - 1
  for ($i = 0; $i -lt $nonBuild; $i++) {
    if ($Shape -eq "fanout") { $name = "leaf-{0:d3}" -f $i }
    elseif ($Shape -eq "mixed" -and $i -lt 6) { $name = "leaf-{0:d3}" -f $i }
    else { $name = "step-{0:d3}" -f $i }
    $taskNames += $name
    $output = "benchmarks/generated/$Name/out/$name.txt"
    $command = "python benchmarks/generated/$Name/write_task.py $name $output"
    $lines += "[tasks.$name]"
    $lines += "cmd = '$command'"
    $lines += "outputs = ['$output']"
    if ($i -gt 0 -and $Shape -ne "fanout") {
      $previous = $taskNames[$i - 1]
      if ($Shape -eq "mixed" -and $i -eq 6) { $previous = "leaf-000" }
      $lines += "deps = ['$previous']"
    }
    $lines += ""
  }
  $buildDeps = if ($Shape -eq "fanout") { $taskNames } else { @($taskNames[-1]) }
  $buildOutput = "benchmarks/generated/$Name/out/build.txt"
  $lines += "[tasks.build]"
  $lines += "cmd = 'python benchmarks/generated/$Name/write_task.py build $buildOutput'"
  $lines += "deps = [$(($buildDeps | ForEach-Object { "'$_'" }) -join ', ')]"
  $lines += "outputs = ['$buildOutput']"
  $lines -join ([Environment]::NewLine) | Set-Content -Encoding UTF8 (Join-Path $dir "Moonforge.toml")
  return (Join-Path $dir "Moonforge.toml")
}

function Measure-MoonForge {
  param([string]$Config, [int]$Jobs)
  $output = Join-Path $repoRoot "tmp/moonforge-benchmarks/output.txt"
  New-Item -ItemType Directory -Force -Path (Split-Path $output) | Out-Null
  $watch = Measure-Command {
    & moon run --target native cmd/main -- run --file $Config build -j $Jobs *> $output
    if ($LASTEXITCODE -ne 0) { throw "MoonForge benchmark failed for $Config" }
  }
  $text = Get-Content $output -Raw
  $executed = [regex]::Match($text, "executed: (\d+)").Groups[1].Value
  $skipped = [regex]::Match($text, "skipped: (\d+)").Groups[1].Value
  [pscustomobject]@{
    wall_ms = [math]::Round($watch.TotalMilliseconds, 2)
    executed = [int]$executed
    skipped = [int]$skipped
  }
}

$cases = @(
  @{ name = "small-chain"; count = 12; shape = "chain" },
  @{ name = "medium-mixed"; count = 48; shape = "mixed" },
  @{ name = "wide-fanout"; count = 33; shape = "fanout" },
  @{ name = "deep-chain"; count = 40; shape = "chain" }
)

$rows = @()
foreach ($case in $cases) {
  $config = Write-Workload $case.name $case.count $case.shape
  $cold = Measure-MoonForge $config $Jobs
  $warm = Measure-MoonForge $config $Jobs
  $rows += [pscustomobject]@{
    workload = $case.name
    tasks = $case.count
    jobs = $Jobs
    cold_wall_ms = $cold.wall_ms
    warm_wall_ms = $warm.wall_ms
    cold_executed = $cold.executed
    warm_executed = $warm.executed
    warm_skipped = $warm.skipped
  }
}

$outputPath = Join-Path $repoRoot $Output
New-Item -ItemType Directory -Force -Path (Split-Path $outputPath) | Out-Null
$rows | Export-Csv -NoTypeInformation -Encoding UTF8 $outputPath
Write-Host "Wrote $outputPath"
$rows | Format-Table -AutoSize
